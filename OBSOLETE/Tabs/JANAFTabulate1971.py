def getCpJANAF1971(species, T):
	tab=getJANAF1971()
	return map(lambda x: getCpJANAFelement1971(tab,species,x),T)

def getCpJANAFelement1971(tab, species, T):
	ind=bs.bisect(tab['T'], T)
	return (tab['h'+species][ind]-tab['h'+species][ind-1])/tab['dT']/tab['W'+species]


def getEnthalpyJANAF1971(species, T):
	tab=getJANAF1971()
	return map(lambda x: getEnthalpyJANAFelement1971(tab,species,x),T)


def getEnthalpyJANAFelement1971(tab, species, T):
	ind=bs.bisect(tab['T'], T)
	return (tab['h'+species][ind]-tab['h'+species][ind-1])/tab['dT']*(T-tab['T'][ind-1])+tab['h'+species][ind-1]

def getEnthalpyPlusFormationJANAF1971(species, T):
	tab=getJANAF1971()
	return map(lambda x: getEnthalpyPlusFormationJANAFelement1971(tab,species,x),T)

def getEnthalpyPlusFormationJANAFelement1971(tab, species, T):
	ind=bs.bisect(tab['T'], T)
	return (tab['h'+species][ind]-tab['h'+species][ind-1])/tab['dT']*(T-tab['T'][ind-1])+tab['h'+species][ind-1]+tab['hf'+species]


def getEntropyJANAFelement1971(tab, species, T):
	ind=bs.bisect(tab['T'], T)
	return (tab['s'+species][ind]-tab['s'+species][ind-1])/tab['dT']*(T-tab['T'][ind-1])+tab['s'+species][ind-1]

def getEntropyJANAF1971(species, T):
	tab=getJANAF1971()
	return map(lambda x: getEntropyJANAFelement1971(tab,species,x),T)


